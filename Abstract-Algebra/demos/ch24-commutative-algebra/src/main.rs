fn cmd_noetherian(args: &[&str]) -> String {
    let n = match parse_uint(args, 0, "n") { Some(x) => x as usize, None => return String::new() };
    if n < 2 { return "n must be at least 2".to_string(); }
    let divs = divisors(n as u64);
    let mut out = format!("Ascending Chain Condition on Z/{}Z\n", n);
    out.push_str("  Ideals:\n");
    for &d in &divs {
        let size = n as u64 / d;
        out.push_str(&format!("    ({}) -- size {}\n", n as u64 / d, size));
    }
    let factors = factor(n as u64);
    let mut current = n as u64;
    let mut chain = vec![current];
    'outer: loop {
        for &(p, _) in &factors {
            if current % p == 0 { current /= p; chain.push(current); continue 'outer; }
        }
        break;
    }
    let chain_str: Vec<String> = chain.iter().map(|&d| {
        format!("({}) [size {}]", n as u64 / d, d)
    }).collect();
    out.push_str(&format!("  Maximal ascending chain: {}\n", chain_str.join(" < ")));
    out.push_str("  Z/nZ is Noetherian (and Artinian): every chain stabilizes.\n");
    out
}

fn cmd_localize(args: &[&str]) -> String {
    let p = match parse_uint(args, 0, "p") { Some(x) => x, None => return String::new() };
    if !is_prime(p) { return format!("{} is not prime.", p); }
    let inverted: Vec<i64> = (1..=20i64).filter(|&b| b % p as i64 != 0).collect();
    let mut out = format!("Localization Z_({}) = Z[1/b : p does not divide b]\n", p);
    out.push_str(&format!("  Inverted (first 10): {:?}\n", &inverted[..inverted.len().min(10)]));
    out.push_str(&format!("  NOT inverted: {}, {}, {}, ...\n", p, 2*p, 3*p));
    out.push_str(&format!("  Z_({}) is a local ring, unique maximal ideal ({})\n", p, p));
    out.push_str(&format!("  Residue field: Z_({}) / ({}) = F_{}\n", p, p, p));
    out.push_str(&format!("  Z_({}) is a DVR with uniformizer {}.\n", p, p));
    out
}

fn cmd_nullstellensatz(args: &[&str]) -> String {
    if args.len() < 2 { return "Usage: nullstellensatz <f coeffs...> <p>".to_string(); }
    let p = match args.last().and_then(|s| s.parse::<u64>().ok()) {
        Some(x) => x, None => return "Last arg must be prime p.".to_string(),
    };
    if !is_prime(p) { return format!("{} is not prime.", p); }
    let coeffs: Vec<i64> = args[..args.len()-1].iter().filter_map(|s| s.parse().ok()).collect();
    let f = Poly::new(coeffs);
    let zeros: Vec<u64> = (0..p).filter(|&x| f.eval_mod(x as i64, p as i64) == 0).collect();
    let mut out = format!("Nullstellensatz over F_{}\n  f(x) = {}\n", p, f);
    if zeros.is_empty() {
        out.push_str("  V(f) = {} (empty)\n  I(V(f)) = (1) = F_p[x]\n");
    } else {
        out.push_str(&format!("  V(f) = {:?} in F_{}\n", zeros, p));
        let mut g = Poly::new(vec![1]);
        for &a in &zeros {
            let linear = Poly::new(vec![-(a as i64), 1]);
            g = g.mul(&linear);
        }
        out.push_str(&format!("  I(V(f)) generated by product(x-a) = {}\n", g));
    }
    out.push_str("  Hilbert Nullstellensatz: over alg. closed field, rad(I(V(J))) = rad(J).\n");
    out
}

fn cmd_krull_z() -> String {
    let primes = primes_up_to(20);
    let mut out = String::from("Krull Dimension of Z\n");
    out.push_str("  Prime ideals: (0), and (p) for each prime p.\n");
    out.push_str("  Prime examples: ");
    out.push_str(&primes.iter().map(|&p| format!("({})", p)).collect::<Vec<_>>().join(", "));
    out.push('\n');
    out.push_str("  Maximal chain: (0) < (p)  length = 1\n");
    out.push_str("  dim Z = 1\n");
    out.push_str("  Z is a Dedekind domain (1-dimensional PID).\n");
    out
}

fn cmd_krull_poly(args: &[&str]) -> String {
    let n = match parse_uint(args, 0, "n") { Some(x) => x as usize, None => return String::new() };
    if n == 0 { return "n must be positive".to_string(); }
    if n > 6 { return "n too large (max 6)".to_string(); }
    let vars: Vec<String> = (1..=n).map(|i| format!("x_{}", i)).collect();
    let ring = format!("k[{}]", vars.join(","));
    let mut out = format!("Krull Dimension of {}\n", ring);
    let mut chain: Vec<String> = vec!["(0)".to_string()];
    for i in 1..=n {
        let ideal_gens: Vec<String> = (1..=i).map(|j| format!("x_{}", j)).collect();
        chain.push(format!("({})", ideal_gens.join(",")));
    }
    out.push_str(&format!("  Chain: {}\n", chain.join(" < ")));
    out.push_str(&format!("  dim {} = {}\n", ring, n));
    out.push_str(&format!("  dim k[x_1,...,x_n] = n for any field k.\n"));
    out
}

fn cmd_primary_decomp(args: &[&str]) -> String {
    let n = match parse_uint(args, 0, "n") { Some(x) => x, None => return String::new() };
    if n < 2 { return "n must be at least 2".to_string(); }
    let factors = factor(n);
    let mut out = format!("Primary Decomposition of (0) in Z/{}Z\n", n);
    out.push_str(&format!("  {} = {}\n", n,
        factors.iter().map(|&(p,e)| if e==1 { format!("{}",p) } else { format!("{}^{}",p,e) }).collect::<Vec<_>>().join(" * ")));
    out.push_str("  Primary components:\n");
    let mut ideals: Vec<String> = Vec::new();
    for &(p, e) in &factors {
        let pk = p.pow(e);
        out.push_str(&format!("    ({}) = ({}) -- {}-primary\n", pk, pk, p));
        ideals.push(format!("({})", pk));
    }
    out.push_str(&format!("  ({}) = {} in Z\n", n, ideals.join(" ∩ ")));
    out.push_str("  Primary decomp: analogue of prime factorization for ideals.\n");
    out
}

fn cmd_integral(args: &[&str]) -> String {
    if args.len() < 2 { return "Usage: integral <a> <monic poly coeffs...>".to_string(); }
    let a = match parse_int(args, 0, "a") { Some(x) => x, None => return String::new() };
    let coeffs: Vec<i64> = args[1..].iter().filter_map(|s| s.parse().ok()).collect();
    if coeffs.is_empty() { return "Provide polynomial coefficients (constant first).".to_string(); }
    let mut monic_coeffs = coeffs.clone();
    let last = monic_coeffs.len() - 1;
    if monic_coeffs[last] != 1 { monic_coeffs[last] = 1; }
    let f = Poly::new(monic_coeffs);
    let val = f.eval(a);
    let mut out = format!("Is {} integral over Z?\n  f(x) = {}\n  f({}) = {}\n", a, f, a, val);
    if val == 0 {
        out.push_str(&format!("  {} IS integral over Z (satisfies f).\n", a));
    } else {
        out.push_str(&format!("  {} does not satisfy this polynomial.\n", a));
        out.push_str(&format!("  (But {} is always integral via f(x) = x - {})\n", a, a));
    }
    out.push_str("  Algebraic integers: sqrt(2) (x^2-2=0), i (x^2+1=0), zeta_n (Phi_n(x)=0).\n");
    out.push_str("  Non-example: 1/2 satisfies 2x-1=0 but no MONIC integer polynomial.\n");
    out
}

