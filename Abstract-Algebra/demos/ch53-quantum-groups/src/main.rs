    out.push_str("  R-matrix for U_q(sl(2)) on V(1)⊗V(1):\n");
    out.push_str("  Basis of V(1)⊗V(1): {v₊⊗v₊, v₊⊗v₋, v₋⊗v₊, v₋⊗v₋}\n\n");
    out.push_str("  R-matrix (quantum R-matrix of U_q(sl(2))):\n");
    out.push_str("       v₊⊗v₊    v₊⊗v₋    v₋⊗v₊    v₋⊗v₋\n");
    out.push_str("  ┌                                         ┐\n");
    out.push_str("  │  q         0         0         0        │  v₊⊗v₊\n");
    out.push_str("  │  0         q-q⁻¹     1         0        │  v₊⊗v₋\n");
    out.push_str("  │  0         1         0         0        │  v₋⊗v₊\n");
    out.push_str("  │  0         0         0         q        │  v₋⊗v₋\n");
    out.push_str("  └                                         ┘\n\n");
    out.push_str("  For q=1 this becomes the permutation matrix (swap operator).\n\n");
    out.push_str("  Verification of YBE for q = 3/2:\n");
