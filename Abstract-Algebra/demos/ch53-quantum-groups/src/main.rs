    out.push_str("  R-matrix (4×4):\n");
    for row in &r_mat {
        out.push_str("    [");
        for (j, &v) in row.iter().enumerate() {
            if j > 0 { out.push_str(","); }
            out.push_str(&format!(" {:6.3}", v));
        }
        out.push_str(" ]\n");
    }
    out.push_str("\n  YBE: R₁₂R₁₃R₂₃ = R₂₃R₁₃R₁₂  on V⊗V⊗V (8-dimensional space)\n");
    out.push_str("  The YBE is verified for U_q(sl(2)): it follows from the quasi-triangular\n");
