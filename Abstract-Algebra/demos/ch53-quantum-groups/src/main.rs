fn default_state() -> StateMap {
    let mut s = state_new();
    state_set_float(&mut s, "q_num", 3.0);
    state_set_float(&mut s, "q_den", 2.0);
    state_set_int(&mut s, "crystal_n", 3);
    s
}

fn run_cmd(cmd: &str, args: &[&str], state: &mut StateMap) -> String {
    match cmd {
        "help" | "h" => show_help(),
        "uq_sl2" => cmd_uq_sl2(),
        "q_number" => {
            let n = args.get(0).and_then(|s| s.parse::<i64>().ok()).unwrap_or(5);
            let qn = args.get(1).and_then(|s| s.parse::<f64>().ok())
                .unwrap_or(state_get_float(state, "q_num").unwrap_or(3.0));
            let qd = args.get(2).and_then(|s| s.parse::<f64>().ok())
                .unwrap_or(state_get_float(state, "q_den").unwrap_or(2.0));
            state_set_float(state, "q_num", qn);
            state_set_float(state, "q_den", qd);
            state_set_int(state, "q_n", n);
            cmd_q_number(n, qn, qd)
        }
        "quantum_dim" => {
            let n = args.get(0).and_then(|s| s.parse::<i64>().ok()).unwrap_or(3);
            let qn = args.get(1).and_then(|s| s.parse::<f64>().ok())
                .unwrap_or(state_get_float(state, "q_num").unwrap_or(3.0));
            let qd = args.get(2).and_then(|s| s.parse::<f64>().ok())
                .unwrap_or(state_get_float(state, "q_den").unwrap_or(2.0));
            state_set_float(state, "q_num", qn);
            state_set_float(state, "q_den", qd);
            state_set_int(state, "qdim_n", n);
            cmd_quantum_dim(n, qn, qd)
        }
        "crystal" => {
            let n = args.get(0).and_then(|s| s.parse::<i64>().ok())
                .unwrap_or(state_get_int(state, "crystal_n").unwrap_or(3));
            state_set_int(state, "crystal_n", n);
            cmd_crystal(n)
        }
        "root_of_unity" => {
            let l = args.get(0).and_then(|s| s.parse::<u64>().ok()).unwrap_or(5);
            state_set_int(state, "root_of_unity_l", l as i64);
            cmd_root_of_unity(l)
        }
        "yang_baxter" => cmd_yang_baxter(),
        "demo" => {
            let mut out = cmd_uq_sl2();
            out.push_str(&cmd_q_number(5, 3.0, 2.0));
            out.push_str(&cmd_crystal(3));
            out.push_str(&cmd_root_of_unity(5));
            out
        }
        _ => format!("Unknown command '{}'. Type 'help'.\n", cmd),
    }
}

fn run_cmd_bool(cmd: &str, args: &[&str], state: &mut StateMap) -> bool {
    if cmd == "quit" || cmd == "exit" || cmd == "q" { return false; }
    let out = run_cmd(cmd, args, state);
    if !out.is_empty() { println!("{}", out); }
    true
}

