    out.push_str("  Connection to Braid Groups:\n");
    out.push_str("  The braid group Bₙ has generators σ₁,...,σₙ₋₁ with:\n");
    out.push_str("    Braid relation: σᵢσᵢ₊₁σᵢ = σᵢ₊₁σᵢσᵢ₊₁\n");
    out.push_str("    Far commutativity: σᵢσⱼ = σⱼσᵢ for |i-j| ≥ 2\n\n");
    out.push_str("  The R-matrix gives a braid group representation:\n");
    out.push_str("    σᵢ ↦ Id^{⊗(i-1)} ⊗ R ⊗ Id^{⊗(n-i-1)}\n");
    out.push_str("  The YBE R₁₂R₁₃R₂₃ = R₂₃R₁₃R₁₂ is exactly the braid relation!\n\n");
    out.push_str("  Jones Polynomial:\n");
    out.push_str("  Closing a braid β ∈ Bₙ gives a link. The Jones polynomial:\n");
    out.push_str("    V_L(q) = trace_{V(1)^{⊗n}}(ρ(β) · K^{⊗n})\n\n");
    out.push_str("  This is the Reshetikhin-Turaev invariant from U_q(sl(2)) representation theory.\n");
