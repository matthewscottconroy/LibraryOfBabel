// [n]_q = (q^n - q^{-n}) / (q - q^{-1})
fn q_integer(n: i64, q: f64) -> f64 {
    if (q - 1.0).abs() < 1e-12 { return n as f64; }
    let qn = q.powi(n as i32);
    let qni = 1.0 / qn;
    let qi = 1.0 / q;
    (qn - qni) / (q - qi)
}

fn q_factorial(n: i64, q: f64) -> f64 {
    (1..=n).map(|k| q_integer(k, q)).product()
}

fn q_binomial(n: i64, k: i64, q: f64) -> f64 {
    if k < 0 || k > n { return 0.0; }
    q_factorial(n, q) / (q_factorial(k, q) * q_factorial(n-k, q))
}

